def test_analysis_is_reproducible_and_lands_in_video_stats_and_gates(clips, tmp_path):
    lib = make_lib(tmp_path)
    clip = put(lib, clips["dup12"])
    a, b = V.analyze(lib, clip), V.analyze(lib, clip)
    assert json.dumps(a["stats"], sort_keys=True) == json.dumps(b["stats"], sort_keys=True)
    st = lib.get(clip)["stats"]
    assert st["motion_fps"] == pytest.approx(12.0, abs=0.3) and st["container_fps"] == 24.0 and st["analyzed_with"].startswith("lampway.video@")
    assert len(lib.get(clip)["gates"]) == 3                                         # a re-analysis replaces its gate rows, never piles them up
    gates = {g["gate"]: g for g in lib.get(clip)["gates"]}
    assert gates["motion_fps_ge_24"]["passed"] == 0 and gates["dup_frames"]["value"] > 0
    row = lib._reader().execute("select motion_fps,dup_ratio from v_video_clips where id=?", (clip,)).fetchone()
    assert row[0] == pytest.approx(12.0, abs=0.3)


def test_refusals_name_the_fix(clips, tmp_path, monkeypatch):
    lib = make_lib(tmp_path)
    png = tmp_path / "p.png"
    Image.new("RGB", (8, 8)).save(png)
    img = put(lib, png, kind="image")
    with pytest.raises(LibraryError, match="not a video: kind is image"):
        V.analyze(lib, img)
    bad = tmp_path / "bad.mp4"
    bad.write_bytes(b"\x00\x00\x00\x18ftypmp42" + b"\x00" * 64)
    broken = put(lib, bad)
    with pytest.raises(LibraryError, match="cannot decode"):
        V.analyze(lib, broken)
    assert "defect:undecodable" in lib.get(broken)["tags"] and lib.get(broken)["status"] == "active"
    clip = put(lib, clips["plain"])
    monkeypatch.setattr(V, "MAX_ANALYZE_S", 1.0)
    with pytest.raises(LibraryError, match="clip longer than 1 s: analyse a range: pass start_s/end_s"):
        V.analyze(lib, clip)
    assert V.analyze(lib, clip, start_s=0.5, end_s=1.4)["stats"]["frame_count"] > 0
    monkeypatch.setattr(V.shutil, "which", lambda n: None)
    with pytest.raises(LibraryError, match="ffmpeg not found on PATH"):
        V.probe(clips["plain"])


