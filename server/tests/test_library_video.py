"""Asset Vault video (specs/asset_library/asset_video.md section 10): clip facts, TRUE motion fps vs container fps, holds and blends, panels, derived artefacts.

Every fixture is generated by ffmpeg in the test (no download): a scrolling pattern so every real frame differs from its neighbours."""
import itertools
import json
import shutil
import subprocess

import numpy as np
import pytest
from PIL import Image

from lampway_server.library import video as V
from lampway_server.library.store import AssetLibrary, LibraryError

pytestmark = pytest.mark.skipif(shutil.which("ffmpeg") is None or shutil.which("ffprobe") is None, reason="ffmpeg + ffprobe needed")
SRC = "testsrc2=size=160x120:rate={r},scroll=horizontal=0.03"


def ff(*args):
    subprocess.run(["ffmpeg", "-v", "error", "-y", *map(str, args)], check=True, timeout=120)


@pytest.fixture(scope="module")
def clips(tmp_path_factory):
    d = tmp_path_factory.mktemp("clips")
    c = {k: d / f"{k}.mp4" for k in ("plain", "dup12", "noisy12", "held5", "blend", "still", "tone", "silent", "split")}
    ff("-f", "lavfi", "-i", SRC.format(r=24), "-t", 3, "-pix_fmt", "yuv420p", c["plain"])
    ff("-f", "lavfi", "-i", SRC.format(r=12), "-t", 3, "-vf", "fps=24,format=yuv420p", c["dup12"])              # 12 fps motion in a 24 fps container
    ff("-f", "lavfi", "-i", SRC.format(r=12), "-t", 3, "-vf", "fps=24,noise=alls=12:allf=t,format=yuv420p", c["noisy12"])   # held frames differ by grain, not by motion
    ff("-f", "lavfi", "-i", SRC.format(r="24/5"), "-t", 3, "-vf", "fps=24,format=yuv420p", c["held5"])          # each picture shown five times: 4.8 fps
    ff("-f", "lavfi", "-i", SRC.format(r=12), "-t", 3, "-vf", "minterpolate=fps=24:mi_mode=blend,format=yuv420p", c["blend"])
    png = d / "still.png"
    Image.fromarray(np.random.default_rng(1).integers(0, 255, (120, 160, 3), dtype=np.uint8)).save(png)
    ff("-loop", 1, "-framerate", 24, "-i", png, "-t", 2, "-pix_fmt", "yuv420p", c["still"])
    ff("-f", "lavfi", "-i", SRC.format(r=24), "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=48000", "-t", 2, "-pix_fmt", "yuv420p", "-shortest", c["tone"])
    ff("-f", "lavfi", "-i", SRC.format(r=24), "-f", "lavfi", "-i", "anullsrc=r=48000:cl=stereo", "-t", 2, "-pix_fmt", "yuv420p", "-shortest", c["silent"])
    ff("-f", "lavfi", "-i", SRC.format(r=24), "-f", "lavfi", "-i", "color=black:size=8x120:rate=24", "-f", "lavfi", "-i", "mandelbrot=size=160x120:rate=24",
       "-t", 2, "-filter_complex", "[0][1][2]hstack=inputs=3,format=yuv420p", c["split"])
    return c


def make_lib(tmp_path):
    ids, clock = itertools.count(1), itertools.count(1000)
    return AssetLibrary(tmp_path / "lib", idgen=lambda: f"id{next(ids):05d}", clock=lambda: float(next(clock)))


def put(lib, path, kind="video", name=None):
    return lib.put({"kind": kind, "name": name or path.stem, "source": {"kind": "t", "key": str(path)}, "files": [{"role": "main", "path": str(path), "storage": "external"}]})["id"]


# 1 -------------------------------------------------------------------------------------------------------------------------------
def test_probe_matches_ffprobe_for_every_fixture(clips):
    for name, path in clips.items():
        p = V.probe(path)
        raw = json.loads(subprocess.run(["ffprobe", "-v", "error", "-show_format", "-show_streams", "-of", "json", str(path)], capture_output=True, text=True).stdout)
        vs = next(s for s in raw["streams"] if s["codec_type"] == "video")
        assert (p["codec"], p["width"], p["height"], p["pix_fmt"]) == (vs["codec_name"], vs["width"], vs["height"], vs["pix_fmt"]), name
        assert p["container_fps"] == pytest.approx(24.0) and p["duration_s"] == pytest.approx(float(raw["format"]["duration"]))
        assert p["frame_count"] > 0                                                          # counted by decoding when the container does not say
        assert p["has_audio"] == (1 if name in ("tone", "silent") else 0), name


# 2 / 3 / 4 -----------------------------------------------------------------------------------------------------------------------
def test_motion_fps_of_duplicated_clip_is_12_not_24(clips):
    plain, dup, held = (V.analyze_motion(clips[k], 24.0) for k in ("plain", "dup12", "held5"))
    assert plain["motion_fps"] == pytest.approx(24.0, abs=0.3) and plain["dup_frames"] == 0 and plain["blend_suspect"] == 0
    assert dup["motion_fps"] == pytest.approx(12.0, abs=0.3) and dup["dup_ratio"] == pytest.approx(0.5, abs=0.05) and dup["longest_hold"] == 1
    assert held["motion_fps"] == pytest.approx(4.8, abs=0.3) and held["longest_hold"] == 4
    assert dup["motion_fps_confidence"] > 0.8


def test_a_held_frame_under_grain_is_still_a_hold(clips):
    """Grain makes every held frame differ a little (about 2 grey levels here) while motion moves about 24: the threshold adapts to the clip, a fixed floor would read 24 fps."""
    n = V.analyze_motion(clips["noisy12"], 24.0)
    assert n["motion_fps"] == pytest.approx(12.0, abs=0.3) and n["dup_ratio"] == pytest.approx(0.5, abs=0.05)


def test_blend_clip_is_flagged_not_misreported(clips):
    b = V.analyze_motion(clips["blend"], 24.0)
    assert b["blend_suspect"] == 1 and b["motion_fps"] is None                                # never "24": the inbetweens are blends of their neighbours


def test_still_clip_has_motion_energy_zero_and_dup_ratio_one(clips):
    s = V.analyze_motion(clips["still"], 24.0)
    assert s["dup_ratio"] == 1.0 and s["motion_energy"] == pytest.approx(0.0, abs=0.05) and s["motion_fps"] == 0.0


# 5 -------------------------------------------------------------------------------------------------------------------------------
def test_split_detector_finds_the_divider_and_rects_sum_to_frame(clips):
    sp = V.detect_panels(clips["split"])
    assert sp["panel_layout"] == "split_front_side"
    rects = sp["panels"]
    assert len(rects) == 2 and rects[0]["x"] == 0 and rects[1]["x"] + rects[1]["w"] == 328
    assert 155 <= rects[0]["w"] <= 165 and sum(r["w"] for r in rects) + sp["divider"]["w"] == 328 and all(r["h"] == 120 for r in rects)
    assert V.detect_panels(clips["plain"])["panel_layout"] == "single"


def test_a_one_pixel_line_on_flat_grey_is_the_divider_not_the_empty_background(tmp_path):
    """The shape of a real split render: two figures on one flat grey, a thin darker line between them, and empty grey either side of it (29 px: under the
    10 % width cap, so the tone contrast, not the cap, is what rejects it)."""
    out = tmp_path / "line.mp4"
    ff("-f", "lavfi", "-i", "color=c=0x7b7b7b:s=320x120:r=24", "-f", "lavfi", "-i", "testsrc2=s=60x60:r=24", "-f", "lavfi", "-i", "testsrc2=s=60x60:r=24", "-t", 2,
       "-filter_complex", "[0][1]overlay=70:30[t];[t][2]overlay=191:30,drawbox=x=159:y=0:w=2:h=120:color=0x5f5f5f:t=fill,format=yuv420p", out)
    sp = V.detect_panels(out)
    assert sp["panel_layout"] == "split_front_side" and 157 <= sp["divider"]["x"] <= 160 and sp["divider"]["w"] <= 4, sp


