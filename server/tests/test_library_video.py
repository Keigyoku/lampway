def test_compare_alignment_lengths_match(clips, tmp_path):
    lib = make_lib(tmp_path)
    a, b = put(lib, clips["plain"]), put(lib, clips["dup12"])
    for align in ("start", "time", "motion"):
        out = V.compare(lib, a, b, align=align)
        assert len(out["a"]) == len(out["b"]) > 0, align
        assert out["a"] == sorted(out["a"]) and out["b"] == sorted(out["b"])          # monotone: a side-by-side never runs backwards


def test_the_tool_surface_returns_ok_or_a_refusal_with_help(clips, tmp_path):
    lib = make_lib(tmp_path)
    clip = put(lib, clips["held5"])
    out = V.handle(lib, {"action": "analyze", "asset_id": clip})
    assert out["ok"] is True and out["stats"]["motion_fps"] == pytest.approx(4.8, abs=0.3)
    bad = V.handle(lib, {"action": "strip", "asset_id": clip, "strip": {"count": 500}})
    assert bad["ok"] is False and "count 8..64" in bad["error"] and bad["help"]
