def test_derived_artefacts_link_with_the_right_relations(clips, tmp_path):
    lib = make_lib(tmp_path)
    clip = put(lib, clips["plain"])
    out = V.derive(lib, clip, ["frame_strip", "proxy", "keyframes"], strip={"count": 8, "size": 128})
    strip = out["frame_strip"]["asset_id"]
    a = lib.get(strip)
    assert a["kind"] == "image" and a["subtype"] == "strip"
    assert {"src": strip, "dst": clip, "type": "derived_from", "role": "frame_strip", "by": "rule"} in a["relations"]
    assert out["proxy"]["frames"] == 24 and all(f["role"] == "proxy" for f in lib.get(clip)["files"] if f["role"] == "proxy")
    kf = lib._reader().execute("select count(*) from embedding where space='video_kf_hist' and sub_key like 'kf:%'").fetchone()[0]
    assert 1 <= kf <= 24
    png = tmp_path / "start.png"
    Image.new("RGB", (16, 16), (9, 9, 9)).save(png)
    anim = tmp_path / "walk.json"
    anim.write_text("{}")
    start = V.attach(lib, clip, png, "start_frame")
    walk = V.attach(lib, clip, anim, "retargeted")
    rels = lib.get(clip)["relations"]
    assert {"src": clip, "dst": start, "type": "generated_from", "role": "start_frame", "by": "rule"} in rels
    assert {"src": clip, "dst": walk, "type": "drives", "role": "", "by": "rule"} in rels and lib.get(walk)["kind"] == "animation"
    with pytest.raises(LibraryError, match="tell me the layout"):
        V.derive(lib, clip, ["split_panels"])


def test_split_panels_become_part_of_the_clip(clips, tmp_path):
    lib = make_lib(tmp_path)
    clip = put(lib, clips["split"])
    V.analyze(lib, clip)
    out = V.derive(lib, clip, ["split_panels"])
    parts = out["split_panels"]["asset_ids"]
    assert len(parts) == 2
    for pid, role in zip(parts, ("panel:front", "panel:side")):
        a = lib.get(pid)
        assert a["kind"] == "video" and a["subtype"] == "split"
        assert {"src": pid, "dst": clip, "type": "part_of", "role": role, "by": "rule"} in a["relations"]
        assert V.probe(a["files"][0]["locations"][0]["path"])["width"] == 160


